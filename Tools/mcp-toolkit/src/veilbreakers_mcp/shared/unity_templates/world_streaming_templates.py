def generate_occlusion_zone_spec(
    door: dict,
    room_bounds: dict,
) -> dict:
    """Generate a portal-based occlusion zone specification.

    Creates an occlusion zone around a door that acts as a portal between
    two spaces.  The zone is inset slightly from the room bounds so it
    sits just inside the doorframe.

    Parameters
    ----------
    door : dict
        Door descriptor with keys: ``position`` (3-list), ``width`` (float),
        ``height`` (float), ``facing`` (str: north/south/east/west).
    room_bounds : dict
        Room bounds with ``min`` (3-list) and ``max`` (3-list) corners.

    Returns
    -------
    dict
        Occlusion zone spec with ``portal_center``, ``portal_extents``,
        ``zone_min``, ``zone_max``, ``facing``, ``door_width``,
        ``door_height`` keys.
    """
    pos = door.get("position", [0, 0, 0])
    width = door.get("width", 1.2)
    height = door.get("height", 2.4)
    facing = door.get("facing", "north")

    # Portal center is at door position
    portal_center = list(pos)

    # Portal extents depend on facing
    if facing in ("north", "south"):
        portal_extents = [width / 2.0, height / 2.0, 0.15]
    else:
        portal_extents = [0.15, height / 2.0, width / 2.0]

    # Zone is room bounds inset by a small margin
    _INSET = 0.1
    r_min = room_bounds.get("min", [0, 0, 0])
    r_max = room_bounds.get("max", [10, 4, 10])

    zone_min = [r_min[0] + _INSET, r_min[1], r_min[2] + _INSET]
    zone_max = [r_max[0] - _INSET, r_max[1], r_max[2] - _INSET]

    return {
        "portal_center": portal_center,
        "portal_extents": portal_extents,
        "zone_min": zone_min,
        "zone_max": zone_max,
        "facing": facing,
        "door_width": width,
        "door_height": height,
    }
